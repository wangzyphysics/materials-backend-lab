const aliases: Record<string, string> = {
  "china": "CHN", "中国": "CHN", "中国大陆": "CHN", "cn": "CHN", "pr china": "CHN", "p.r. china": "CHN",
  "united states": "USA", "us": "USA", "united kingdom": "GBR", "uk": "GBR", "gb": "GBR",
  "south korea": "KOR", "republic of korea": "KOR", "korea": "KOR", "kr": "KOR",
  "de": "DEU", "fr": "FRA", "jp": "JPN", "in": "IND", "ca": "CAN", "au": "AUS",
};
export function countryCode(value: string): string | null {
  const normalized = value.trim().toLowerCase();
  return (Object.hasOwn(aliases, normalized) ? aliases[normalized] : undefined) ?? mapCountries.find(country => country.code.toLowerCase() === normalized || country.name.toLowerCase() === normalized)?.code ?? null;
}
export function aggregateCountries(values: string[], minimum = 3) {
  const counts = new Map<string, number>();
  let unrecognized = 0;
  for (const value of values) {
    const code = countryCode(value);
    if (code) counts.set(code, (counts.get(code) ?? 0) + 1);
    else unrecognized++;
  }
  const regions = [...counts].filter(([, count]) => count >= minimum).map(([countryCode, users]) => ({ countryCode, users })).sort((a, b) => b.users - a.users || a.countryCode.localeCompare(b.countryCode));
  return { regions, unrecognized, withheld: [...counts].filter(([, count]) => count < minimum).reduce((sum, [, count]) => sum + count, 0) };
}
